"""File storage abstraction for uploaded documents.

Keys are generated by the server (`users/{user_id}/{document_id}{ext}`); client filenames never
reach the storage layer, which removes path traversal by construction. Backends still validate keys.
"""

from __future__ import annotations

import re
from typing import Protocol

_KEY_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._/-]{0,500}$")


class StorageError(Exception):
    pass


def validate_key(key: str) -> str:
    if not _KEY_RE.match(key) or ".." in key.split("/") or "//" in key:
        raise StorageError("Invalid storage key.")
    return key


class StorageBackend(Protocol):
    name: str

    async def save(self, key: str, data: bytes, content_type: str) -> None: ...

    async def read(self, key: str) -> bytes: ...

    async def delete(self, key: str) -> None: ...

    async def exists(self, key: str) -> bool: ...
